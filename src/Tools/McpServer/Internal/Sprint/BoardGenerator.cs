internal static class BoardGenerator
{
    public static async Task GenerateAllBoardsAsync(string projectRoot, CancellationToken ct)
    {
        var items = await BacklogRepository.LoadAllBacklogsAsync(projectRoot, ct).ConfigureAwait(false);
        var backlogsDir = BacklogRepository.GetBacklogsDir(projectRoot);

        await GenerateProductBacklogAsync(backlogsDir, items, ct).ConfigureAwait(false);
        await GenerateActiveSprintAsync(projectRoot, backlogsDir, items, ct).ConfigureAwait(false);
        await GenerateReadmeAsync(backlogsDir, items, ct).ConfigureAwait(false);
    }

    private static async Task GenerateProductBacklogAsync(string backlogsDir, List<BacklogItemModel> items, CancellationToken ct)
    {
        var sb = new StringBuilder();
        sb.AppendLine("<!-- GENERATED: do not edit manually. Generated by vk-blocks-be-manager -->");
        sb.AppendLine("# 📋 Product Backlog (Master Index)");
        sb.AppendLine();
        sb.AppendLine("VK.Blocks 全モジュールの未完了・保留タスク一覧です。優先度（P0〜P3）順、および父レベル（Pillar）モジュール別に集約されています。");
        sb.AppendLine();

        // High priority focus queue: top items currently doing or P0/P1
        var hotItems = items
            .Where(i => i.FrontMatter.Status == "doing" || i.FrontMatter.Priority == "P0" || i.FrontMatter.Priority == "P1")
            .Where(i => i.FrontMatter.Status != "done" && i.FrontMatter.Status != "dropped")
            .OrderBy(i => i.FrontMatter.Status == "doing" ? 0 : 1)
            .ThenBy(i => i.FrontMatter.Priority switch
            {
                "P0" => 0,
                "P1" => 1,
                "P2" => 2,
                "P3" => 3,
                _ => 4
            })
            .ThenBy(i => i.FrontMatter.Rank ?? int.MaxValue)
            .Take(8)
            .ToList();

        if (hotItems.Count > 0)
        {
            sb.AppendLine("## 🔥 Focus Queue (In Progress & High Priority)");
            sb.AppendLine();
            sb.AppendLine("| ID | Priority | Points | Ready | Module | Status | Title |");
            sb.AppendLine("|:---:|:---:|:---:|:---:|:---:|:---:|---|");
            foreach (var hi in hotItems)
            {
                var pIcon = hi.FrontMatter.Priority switch
                {
                    "P0" => "🚨 P0",
                    "P1" => "🔴 P1",
                    "P2" => "🟡 P2",
                    "P3" => "🔵 P3",
                    _ => hi.FrontMatter.Priority
                };
                var relPath = $"./{hi.FrontMatter.Module}/{Path.GetFileName(hi.FilePath)}";
                var statusIcon = hi.FrontMatter.Status == "doing" ? "🏃 `doing`" : $"`{hi.FrontMatter.Status}`";
                var pts = hi.FrontMatter.Points.HasValue ? $"{hi.FrontMatter.Points} pts" : "-";
                var rdy = hi.FrontMatter.Ready ? "✅" : "—";
                sb.AppendLine($"| [{hi.FrontMatter.Id}]({relPath}) | {pIcon} | {pts} | {rdy} | `{hi.FrontMatter.Module}` | {statusIcon} | {hi.FrontMatter.Title} |");
            }
            sb.AppendLine();
        }

        var nonArchived = items
            .Where(i => i.FrontMatter.Status != "done" && i.FrontMatter.Status != "dropped")
            .OrderBy(i => i.FrontMatter.Priority switch
            {
                "P0" => 0,
                "P1" => 1,
                "P2" => 2,
                "P3" => 3,
                _ => 4
            })
            .ThenBy(i => i.FrontMatter.Rank ?? int.MaxValue)
            .ThenBy(i => i.FrontMatter.Module)
            .ThenBy(i => i.FrontMatter.Id)
            .ToList();

        var modules = nonArchived.Select(i => i.FrontMatter.Module).Distinct().OrderBy(m => m == "Core" ? "00_Core" : m).ToList();

        foreach (var mod in modules)
        {
            var modItems = nonArchived.Where(i => i.FrontMatter.Module == mod).ToList();
            var icon = GetModuleIcon(mod);
            sb.AppendLine($"## {icon} {mod} ({modItems.Count})");
            sb.AppendLine();
            sb.AppendLine("| ID | Priority | Points | Ready | Category | Status | Title | Sprint |");
            sb.AppendLine("|:---:|:---:|:---:|:---:|:---:|:---:|---|:---:|");

            foreach (var item in modItems)
            {
                var fm = item.FrontMatter;
                var pIcon = fm.Priority switch
                {
                    "P0" => "🚨 P0",
                    "P1" => "🔴 P1",
                    "P2" => "🟡 P2",
                    "P3" => "🔵 P3",
                    _ => fm.Priority
                };
                var relPath = $"./{fm.Module}/{Path.GetFileName(item.FilePath)}";
                var sprintText = string.IsNullOrEmpty(fm.Sprint) ? "-" : fm.Sprint;
                var catText = string.IsNullOrEmpty(fm.Category) ? fm.Type : fm.Category;
                var pts = fm.Points.HasValue ? $"{fm.Points} pts" : "-";
                var rdy = fm.Ready ? "✅" : "—";
                sb.AppendLine($"| [{fm.Id}]({relPath}) | {pIcon} | {pts} | {rdy} | `{catText}` | `{fm.Status}` | {fm.Title} | {sprintText} |");
            }
            sb.AppendLine();
        }

        var path = Path.Combine(backlogsDir, "Product_Backlog.md");
        await File.WriteAllTextAsync(path, sb.ToString(), ct).ConfigureAwait(false);
    }

    private static async Task GenerateActiveSprintAsync(string projectRoot, string backlogsDir, List<BacklogItemModel> items, CancellationToken ct)
    {
        var activeSprint = await FindActiveSprintAsync(projectRoot, ct).ConfigureAwait(false);

        var sb = new StringBuilder();
        sb.AppendLine("<!-- GENERATED: do not edit manually. Generated by vk-blocks-be-manager -->");

        if (!activeSprint.HasValue)
        {
            sb.AppendLine("# 🚀 Current Sprint");
            sb.AppendLine();
            sb.AppendLine("> 現在アクティブな Sprint はありません。Skill `/vk-sprint-plan` または MCP ツール `vk_be_sprint_start` で開始してください。");
        }
        else
        {
            var active = activeSprint.Value;
            var sfm = active.FrontMatter;
            sb.AppendLine($"# 🚀 Current Sprint: {sfm.Id}");
            sb.AppendLine();

            var sprintId = sfm.Id;
            var sprintItems = items.Where(i => i.FrontMatter.Sprint == sprintId || sfm.Committed.Contains(i.FrontMatter.Id) || (i.FrontMatter.LegacyId != null && sfm.Committed.Contains(i.FrontMatter.LegacyId))).ToList();

            var todo = sprintItems.Where(i => i.FrontMatter.Status == "todo" || i.FrontMatter.Status == "icebox").ToList();
            var doing = sprintItems.Where(i => i.FrontMatter.Status == "doing").ToList();
            var done = sprintItems.Where(i => i.FrontMatter.Status == "done").ToList();

            var committedPts = sfm.CommittedPoints ?? sprintItems.Sum(i => i.FrontMatter.Points ?? 0);
            var capacityPts = sfm.CapacityPoints?.ToString() ?? "N/A";

            // Timebox and progress calculation
            var hasStart = DateOnly.TryParse(sfm.Start, out var startDate);
            var hasEnd = DateOnly.TryParse(sfm.End, out var endDate);
            var todayDate = DateOnly.FromDateTime(DateTime.Today);
            int totalDays = (hasStart && hasEnd) ? Math.Max(1, endDate.DayNumber - startDate.DayNumber) : 7;
            int currentDay = hasStart ? Math.Clamp(todayDate.DayNumber - startDate.DayNumber + 1, 1, totalDays + 1) : 1;
            int remainingDays = hasEnd ? Math.Max(0, endDate.DayNumber - todayDate.DayNumber) : 0;

            var donePoints = done.Sum(i => i.FrontMatter.Points ?? 0);
            var doingPoints = doing.Sum(i => i.FrontMatter.Points ?? 0);
            var todoPoints = todo.Sum(i => i.FrontMatter.Points ?? 0);
            var totalTrackedPoints = Math.Max(committedPts, donePoints + doingPoints + todoPoints);
            var doneRate = totalTrackedPoints > 0 ? (donePoints / (double)totalTrackedPoints * 100) : 0;

            string paceStatus = "🟢 On Track";
            if (totalTrackedPoints > 0 && totalDays > 0)
            {
                double timeElapsedRate = Math.Clamp(currentDay / (double)totalDays * 100, 0, 100);
                if (doneRate < timeElapsedRate - 30) paceStatus = "🔴 Behind Pace";
                else if (doneRate < timeElapsedRate - 15) paceStatus = "🟡 At Risk";
            }

            sb.AppendLine($"**Goal**: {sfm.Goal}  ");
            sb.AppendLine($"**Period**: {sfm.Start} ~ {sfm.End} (Day {currentDay} of {totalDays}, {remainingDays} days left)  ");
            sb.AppendLine($"**Commitment**: {committedPts} pts (Capacity: {capacityPts} pts)  ");
            sb.AppendLine($"**Progress**: {paceStatus} | Done: {donePoints} / {totalTrackedPoints} pts ({doneRate:F0}%) | Doing: {doingPoints} pts | Todo: {todoPoints} pts  ");
            sb.AppendLine($"**Sprint Spec**: [_sprints/{Path.GetFileName(active.FilePath)}](./Sprints/{Path.GetFileName(active.FilePath)})");
            sb.AppendLine();

            // Check blockers from sprint file: supports indented Daily Standup format and direct lines
            var sprintFileContent = await File.ReadAllTextAsync(active.FilePath, ct).ConfigureAwait(false);
            var blockerMatches = Regex.Matches(sprintFileContent, @"^\s*-\s*🚧\s*(?:\*\*Blocker\*\*:\s*)?(.+)$", RegexOptions.Multiline);
            var activeBlockers = new List<string>();
            foreach (Match b in blockerMatches)
            {
                var val = b.Groups[1].Value.Trim();
                var isNone = val.Equals("なし", StringComparison.OrdinalIgnoreCase) ||
                             val.Equals("None", StringComparison.OrdinalIgnoreCase) ||
                             val.Equals("N/A", StringComparison.OrdinalIgnoreCase) ||
                             val.Equals("無し", StringComparison.OrdinalIgnoreCase) ||
                             val.Equals("-", StringComparison.OrdinalIgnoreCase);

                if (!isNone && !string.IsNullOrWhiteSpace(val))
                {
                    activeBlockers.Add(val);
                }
            }

            if (activeBlockers.Count > 0)
            {
                sb.AppendLine("## 🚧 Active Blockers");
                foreach (var blocker in activeBlockers)
                {
                    sb.AppendLine($"- ⚠️ {blocker}");
                }
                sb.AppendLine();
            }

            sb.AppendLine($"## 🏃 Doing ({doing.Count})");
            if (doing.Count == 0) sb.AppendLine("_着手中のタスクはありません_");
            else
            {
                foreach (var it in doing)
                {
                    var rel = $"./{it.FrontMatter.Module}/{Path.GetFileName(it.FilePath)}";
                    var pts = it.FrontMatter.Points.HasValue ? $", {it.FrontMatter.Points} pts" : "";
                    sb.AppendLine($"- [ ] [{it.FrontMatter.Id}: {it.FrontMatter.Title}]({rel}) ({it.FrontMatter.Priority}{pts})");
                }
            }
            sb.AppendLine();

            sb.AppendLine($"## 📝 Todo ({todo.Count})");
            if (todo.Count == 0) sb.AppendLine("_Todo はありません_");
            else
            {
                foreach (var it in todo)
                {
                    var rel = $"./{it.FrontMatter.Module}/{Path.GetFileName(it.FilePath)}";
                    var pts = it.FrontMatter.Points.HasValue ? $", {it.FrontMatter.Points} pts" : "";
                    sb.AppendLine($"- [ ] [{it.FrontMatter.Id}: {it.FrontMatter.Title}]({rel}) ({it.FrontMatter.Priority}{pts})");
                }
            }
            sb.AppendLine();

            sb.AppendLine($"## ✅ Done ({done.Count})");
            if (done.Count == 0) sb.AppendLine("_完了タスクはまだありません_");
            else
            {
                foreach (var it in done)
                {
                    var rel = $"./{it.FrontMatter.Module}/{Path.GetFileName(it.FilePath)}";
                    var pts = it.FrontMatter.Points.HasValue ? $" ({it.FrontMatter.Points} pts)" : "";
                    sb.AppendLine($"- [x] [{it.FrontMatter.Id}: {it.FrontMatter.Title}]({rel}){pts}");
                }
            }
            sb.AppendLine();

            if (sfm.ScopeChanges.Count > 0)
            {
                sb.AppendLine("## 📋 Scope Changes");
                sb.AppendLine();
                sb.AppendLine("| Date | Action | Task ID | Reason |");
                sb.AppendLine("|:---:|:---:|:---:|---|");
                foreach (var sc in sfm.ScopeChanges)
                {
                    var actBadge = sc.Action.Equals("added", StringComparison.OrdinalIgnoreCase) ? "➕ Added" : "➖ Removed";
                    sb.AppendLine($"| {sc.Date} | {actBadge} | `{sc.Id}` | {sc.Reason} |");
                }
                sb.AppendLine();
            }
        }

        var path = Path.Combine(backlogsDir, "Active_Sprint.md");
        await File.WriteAllTextAsync(path, sb.ToString(), ct).ConfigureAwait(false);
    }

    private static async Task GenerateReadmeAsync(string backlogsDir, List<BacklogItemModel> items, CancellationToken ct)
    {
        var total = items.Count;
        var done = items.Count(i => i.FrontMatter.Status == "done");
        var active = items.Count(i => i.FrontMatter.Status != "done" && i.FrontMatter.Status != "dropped");
        var doing = items.Count(i => i.FrontMatter.Status == "doing");

        var sb = new StringBuilder();
        sb.AppendLine("<!-- GENERATED: do not edit manually. Generated by vk-blocks-be-manager -->");
        sb.AppendLine("# 📚 VK.Blocks Backlog Dashboard");
        sb.AppendLine();
        sb.AppendLine("個人開発のための決定論的 Sprint / Backlog 管理システムです。");
        sb.AppendLine("すべての状態は各タスクファイルの **YAML Front-Matter** に集約され、本ドキュメントおよび各種ボードはツールにより自動生成されます（**Zero git-mv 原則**）。");
        sb.AppendLine();
        sb.AppendLine("## 📊 Summary");
        sb.AppendLine();
        sb.AppendLine($"| Total Tracked | Active Backlogs | In Progress (`doing`) | Completed (`done`) |");
        sb.AppendLine($"|:---:|:---:|:---:|:---:|");
        sb.AppendLine($"| **{total}** | **{active}** | **{doing}** | **{done}** |");
        sb.AppendLine();

        // Hot queue in README as well
        var hotItems = items
            .Where(i => i.FrontMatter.Status == "doing" || i.FrontMatter.Priority == "P0" || i.FrontMatter.Priority == "P1")
            .Where(i => i.FrontMatter.Status != "done" && i.FrontMatter.Status != "dropped")
            .OrderBy(i => i.FrontMatter.Status == "doing" ? 0 : 1)
            .ThenBy(i => i.FrontMatter.Priority switch
            {
                "P0" => 0,
                "P1" => 1,
                "P2" => 2,
                "P3" => 3,
                _ => 4
            })
            .ThenBy(i => i.FrontMatter.Rank ?? int.MaxValue)
            .Take(5)
            .ToList();

        if (hotItems.Count > 0)
        {
            sb.AppendLine("## 🔥 Quick Focus Queue (Latest Active Items)");
            sb.AppendLine();
            foreach (var hi in hotItems)
            {
                var rel = $"./{hi.FrontMatter.Module}/{Path.GetFileName(hi.FilePath)}";
                var badge = hi.FrontMatter.Status == "doing" ? "🏃 `doing`" : $"`{hi.FrontMatter.Priority}`";
                var pts = hi.FrontMatter.Points.HasValue ? $" ({hi.FrontMatter.Points} pts)" : "";
                sb.AppendLine($"- {badge} **[{hi.FrontMatter.Id}]({rel})**: {hi.FrontMatter.Title} (`{hi.FrontMatter.Module}`{pts})");
            }
            sb.AppendLine();
        }

        sb.AppendLine("## 🧭 Navigation");
        sb.AppendLine();
        sb.AppendLine("- [🚀 Current Active Sprint](./Active_Sprint.md) — 今週コミットしている作業スコープ（1クリックで直行）");
        sb.AppendLine("- [📋 Product Backlog Master](./Product_Backlog.md) — 全モジュールの優先度付きマスターリスト（未完了のみ抽出）");
        sb.AppendLine("- [📊 Project Health Scorecard](./Health_Scorecard.md) — アーキテクチャ遵守度スコア・ベロシティ推移");
        sb.AppendLine("- [📁 Sprint Archives](./_sprints/) — 過去の Sprint 履歴と振り返り (Retro)");
        sb.AppendLine();
        sb.AppendLine("## 🛠️ Management via Skills / MCP");
        sb.AppendLine();
        sb.AppendLine("- `/vk-add-backlog`: 負債・監査指摘・新機能を front-matter 付きで追加（グローバル自增 ID: `#NNN`）");
        sb.AppendLine("- `/vk-backlog-refine`: 未見積タスクの見積もり付与・順位整理・DoR 判定（Ready 化）");
        sb.AppendLine("- `/vk-sprint-plan`: 1週間の Sprint を開始し Goal とタスクを選定（容量チェック機能付き）");
        sb.AppendLine("- `/vk-sprint-daily`: 毎日の進捗とブロッカーを記録");
        sb.AppendLine("- `/vk-sprint-task-start`: タスクを `doing` に遷移しブランチ・コミット規約を確認（着手日記録）");
        sb.AppendLine("- `/vk-sprint-task-done`: DoD 検証・コミット収集・インプレース完了（Zero git-mv）");
        sb.AppendLine("- `/vk-sprint-review`: Sprint を完了し Review / Retro (KPT) を記録し Try を自動起票");
        sb.AppendLine();

        var path = Path.Combine(backlogsDir, "README.md");
        await File.WriteAllTextAsync(path, sb.ToString(), ct).ConfigureAwait(false);
    }

    public static async Task<(SprintFrontMatter FrontMatter, string FilePath)?> FindActiveSprintAsync(string projectRoot, CancellationToken ct)
    {
        var sprintsDir = BacklogRepository.GetSprintsDir(projectRoot);
        if (!Directory.Exists(sprintsDir)) return null;

        var files = Directory.GetFiles(sprintsDir, "*.md");
        foreach (var file in files)
        {
            var text = await File.ReadAllTextAsync(file, ct).ConfigureAwait(false);
            if (BacklogRepository.TryParseFrontMatter<SprintFrontMatter>(text, out var fm, out _) && fm != null)
            {
                if (string.Equals(fm.Status, "active", StringComparison.OrdinalIgnoreCase))
                {
                    return (fm, file);
                }
            }
        }
        return null;
    }

    private static string GetModuleIcon(string moduleName) => moduleName.ToLowerInvariant() switch
    {
        "core" => "🏗️",
        "ai" => "🧠",
        "authentication" => "🔑",
        "authorization" => "🔐",
        "persistence" => "💾",
        "multitenancy" => "🏢",
        "infrastructure" => "⚙️",
        "observability" => "📈",
        "resilience" => "🛡️",
        "storage" => "📦",
        "web" => "🌐",
        "tools" => "🛠️",
        "validation" => "✨",
        "vectorsearch" or "vectorstore" => "🔍",
        "security" => "🔒",
        "labs" => "🧪",
        _ => "📋"
    };
}
